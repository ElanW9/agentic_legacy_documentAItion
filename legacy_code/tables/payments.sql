CREATE TABLE PAYMENTS (
  PAY_ID      NUMBER(12)    NOT NULL,
  INV_ID      NUMBER(12)    NOT NULL,
  PAY_DT      DATE          DEFAULT SYSDATE,
  PAY_AMT     NUMBER(12,2)  NOT NULL,
  PAY_METHOD  VARCHAR2(2),
  REF_TXT     VARCHAR2(100),
  CREATED_BY  VARCHAR2(30),
  CONSTRAINT PAYMENTS_PK PRIMARY KEY (PAY_ID),
  CONSTRAINT PAY_INV_FK FOREIGN KEY (INV_ID) REFERENCES INVOICES (INV_ID)
);

COMMENT ON COLUMN PAYMENTS.PAY_METHOD IS 'BT=bank transfer, CC=credit card';
